#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────
# seal_m5_freeze.sh — One-shot freeze sealer.
#
# Run from ~/.lightning_studio/TASB_Refactor/ AFTER freeze_m5.sh has built
# results/M5_FROZEN_20260530/. This finishes the job:
#
#   1. Runs tasb_m5_recut.py on the frozen CSV, capturing console output to
#      m5_recut_console.txt via tee.
#   2. Writes m5_console.txt with the canonical M5 aggregate numbers (the
#      summary block, not the 3780-row step log — those live in the CSV).
#   3. SHA-256 checksums every artifact into manifest.sha256 so the freeze
#      is tamper-evident.
#   4. Prints a final tree showing the sealed directory.
#
# No more manual pasting. No nano / vim required. ~1 second runtime.
# ─────────────────────────────────────────────────────────────────────────

set -euo pipefail

FREEZE_DIR="results/M5_FROZEN_20260530"
SOURCE_CSV="$FREEZE_DIR/tasb_m5_faithfulness_20260530_133305.csv"

echo "═══════════════════════════════════════════════════════════════════════"
echo "  M5 FREEZE — sealing $FREEZE_DIR"
echo "═══════════════════════════════════════════════════════════════════════"
echo

# ─── Sanity checks ─────────────────────────────────────────────────────
if [[ ! -d "$FREEZE_DIR" ]]; then
    echo "ERROR: $FREEZE_DIR not found. Run ./freeze_m5.sh first."
    exit 1
fi

if [[ ! -f "$SOURCE_CSV" ]]; then
    echo "ERROR: $SOURCE_CSV not found inside the freeze directory."
    exit 1
fi

if [[ ! -f tasb_m5_recut.py ]]; then
    echo "ERROR: tasb_m5_recut.py not found in TASB_Refactor/ root."
    exit 1
fi

# ─── Step 1: Run recut with tee ─────────────────────────────────────────
echo "─── Running recut → m5_recut_console.txt ───"
python tasb_m5_recut.py "$SOURCE_CSV" 2>&1 \
    | tee "$FREEZE_DIR/m5_recut_console.txt"
echo

# ─── Step 2: Write m5_console.txt (the canonical aggregate, no step log) ──
echo "─── Writing m5_console.txt ───"
cat > "$FREEZE_DIR/m5_console.txt" << 'CONSOLE_EOF'
