# ─── Step 3: SHA-256 manifest (tamper-evident sealing) ──────────────────
echo "─── Computing SHA-256 manifest ───"
(
    cd "$FREEZE_DIR"
    # Hash everything except the manifest itself
    sha256sum *.csv *.py *.txt *.md 2>/dev/null \
        | sort > manifest.sha256
)
echo "  $FREEZE_DIR/manifest.sha256 written"
echo

# ─── Step 4: Final tree ─────────────────────────────────────────────────
echo "═══════════════════════════════════════════════════════════════════════"
echo "  M5 FREEZE SEALED"
echo "═══════════════════════════════════════════════════════════════════════"
echo
