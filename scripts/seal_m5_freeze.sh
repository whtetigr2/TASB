echo
echo "  Manifest:"
sed 's/^/    /' "$FREEZE_DIR/manifest.sha256"
echo
echo "  To verify integrity later:"
echo "    cd $FREEZE_DIR && sha256sum -c manifest.sha256"
echo
echo "  M5 is now sealed and citeable. Ready for M6."
echo "═══════════════════════════════════════════════════════════════════════"
